#!/usr/bin/env python3
"""見出しから検索語を作り、一次資料に当てる価値のある題材だけを選ぶ。

**この2つは必ず対で使う。** 検索語だけ短くすると国会会議録には当たるように
なるが、当たった発言は題材と無関係なものばかりになる（実測: 見出しの先頭
40字では12件中0件しか当たらず、名詞2〜3語にすると12件中12件当たったが、
中身は消費税減税の見出しに対して憲法審査会の答弁、年金の見出しに対して
NISA の答弁、というありさまだった）。

そこで、当たりやすくする（extract）のと同時に、**そもそも国会で議論され
うる題材だけに絞る**（is_policy_topic）。天気やスポーツの見出しに国会答弁を
探しに行けば、無関係な発言しか返ってこないのは当然だからである。
関連性そのものの検証は evidence.find_passage が担う。
"""

from __future__ import annotations

from janome.tokenizer import Tokenizer

# 生成に数百ミリ秒かかるので、モジュールに1つだけ持つ
_TOKENIZER = Tokenizer()


def tokenize(text: str):
    """形態素に分ける。生成の重い Tokenizer を1つだけ共有するための入口。

    テロップの改行位置（telop.py）も形態素の切れ目を使うので、
    そちらからもこれを呼ぶ。
    """
    return _TOKENIZER.tokenize(text)

# ニュース見出しに頻出するが、題材を絞る力が無い語。
# 元号・年度は janome が固有名詞として拾うため優先度が最上位になってしまい、
# 「令和7年度決算」の見出しで検索語が「令和」から始まって年金の話が
# どこかへ行く、という外し方をしていた。固有名詞だから強い語とは限らない。
STOP = {
    "発言", "問題", "発表", "報道", "会見", "表明", "指摘", "批判", "議論", "対応",
    "検討", "方針", "見通し", "可能性", "必要", "考え", "状況", "影響", "結果",
    "今日", "今回", "現在", "初", "中", "後", "前", "件", "者", "的", "化", "性",
    "速報", "独自", "詳報", "一覧", "予定", "開始", "実施",
    "令和", "平成", "昭和", "年度", "今年", "来年", "昨年",
}

# 国会で議論されうる題材の目印。1語も入っていない見出しは一次資料に
# 当てに行かない。天気・スポーツ・芸能はここで落ちる。
POLICY = (
    "政府", "首相", "総理", "官邸", "内閣", "閣議", "大臣", "官房", "省", "庁",
    "国会", "衆院", "参院", "衆議院", "参議院", "議員", "答弁", "委員会", "審議",
    "法案", "法律", "改正", "制度", "条例", "条約", "規制", "指針", "ガイドライン",
    "予算", "税", "税制", "減税", "増税", "財政", "国債", "補助", "給付", "助成",
    "年金", "保険", "医療", "介護", "福祉", "子育て", "教育", "雇用", "賃金",
    "外交", "防衛", "自衛隊", "安全保障", "米軍", "基地", "領土", "領海", "拉致",
    "移民", "外国人", "入管", "難民", "ビザ", "在留",
    "物価", "経済", "景気", "金利", "日銀", "為替", "円安", "円高",
    "エネルギー", "原発", "再稼働", "電気", "脱炭素", "温暖化",
    "選挙", "政党", "自民", "立憲", "維新", "公明", "共産", "国民民主", "参政",
    "農業", "漁業", "食料", "物流", "交通", "住宅", "地方", "過疎", "人口", "少子化",
    "災害", "防災", "復興", "感染", "ワクチン", "犯罪", "警察", "司法", "裁判",
)

MAX_KEYWORDS = 3

# 検索語がこの数に満たない見出しは扱わない。国会会議録APIの any は
# 空白区切りのAND検索なので語数が少ないほど当たりやすくなるが、
# 1語では「その語がどこかに出てくる発言」しか区別できず、
# evidence.find_passage の近接判定（異なる語が同じ文脈に複数現れること）が
# 成立しない。関連性を確かめられない題材は最初から採らない。
MIN_KEYWORDS = 2


def is_policy_topic(title: str) -> bool:
    """国会で議論されうる題材か。"""
    return any(w in title for w in POLICY)


def extract(title: str, limit: int = MAX_KEYWORDS) -> list[str]:
    """見出しから検索語になる名詞を拾う。固有名詞（人名・組織名）を優先する。

    固有名詞が先頭に来るのは、国会会議録の全文検索で題材を絞り込む力が
    一般名詞よりはるかに強いため（「片山」「竹島」「熊本」など）。
    """
    propers: list[str] = []
    generals: list[str] = []
    for tok in tokenize(title):
        pos = tok.part_of_speech.split(",")
        if pos[0] != "名詞":
            continue
        w = tok.surface
        if len(w) < 2 or w in STOP or w.isdigit():
            continue
        if pos[1] == "固有名詞":
            if w not in propers:
                propers.append(w)
        elif pos[1] in ("一般", "サ変接続"):
            if w not in generals:
                generals.append(w)
    return (propers + generals)[:limit]
